function mergeLocale(partial: Partial<Record<string, string>>): Record<string, string> {
  const merged: Record<string, string> = { ...enUS };
  for (const key of Object.keys(partial)) {
    const value = partial[key];
    if (value !== undefined) merged[key] = value;
  }
  return merged;
}

/** Every locale but English is a chunk of its own, so a page downloads one language. */
const localeLoaders: Record<Exclude<Locale, 'en-US'>, () => Promise<Partial<Record<string, string>>>> = {
  'zh-CN': () => import('./locales/zh-CN').then((module) => module.zhCNLocale),
  'ja-JP': () => import('./locales/ja-JP').then((module) => module.jaJPLocale),
  'de-DE': () => import('./locales/de-DE').then((module) => module.deDELocale),
  'fr-FR': () => import('./locales/fr-FR').then((module) => module.frFRLocale),
};

export function isLocale(value: string): value is Locale {
  return (LOCALES as readonly string[]).includes(value);
}

function resolveBrowserLocale(): Locale {
  if (typeof navigator === 'undefined') return 'en-US';

  const candidates = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const raw of candidates) {
    if (!raw) continue;

    if (isLocale(raw)) return raw;

    const normalized = raw.replace('_', '-');
    if (isLocale(normalized)) return normalized;

    const base = normalized.toLowerCase().split('-')[0];
    if (base === 'zh') return 'zh-CN';
    if (base === 'ja') return 'ja-JP';
    if (base === 'de') return 'de-DE';
    if (base === 'fr') return 'fr-FR';
    if (base === 'en') return 'en-US';
  }

  return 'en-US';
}

/** User manual choice in localStorage wins; otherwise match browser language. */
function readInitialLocale(): Locale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && isLocale(stored)) return stored;
  } catch {
    // Storage blocked (privacy mode, sandboxed iframe): fall back to the browser locale.
  }
  return resolveBrowserLocale();
}

let locale: Locale = readInitialLocale();
let messages: Record<string, string> = enUS;

/**
 * Resolves once the current locale's strings are in (English is built in). main.tsx renders after
 * it, so no screen shows English first. If the chunk cannot load, this visit stays in English.
 */
export const localeReady: Promise<void> =
  locale === 'en-US'
    ? Promise.resolve()
    : localeLoaders[locale]().then(
        (partial) => {
          messages = mergeLocale(partial);
        },
        () => {
          locale = 'en-US';
        },
      );

export function getLocale(): Locale {
  return locale;
}

/** Persist manual locale choice; call sites reload the page after switching. */
export function setLocale(next: Locale) {
  locale = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    // Not persisted; the choice still applies until reload.
  }
}

export function t(key: string): string {
  return messages[key] ?? key;
}

/** `key_one` or `key_other` for `count` under the current locale's plural rules (CLDR). */
export function pluralKey(key: string, count: number): string {
  return new Intl.PluralRules(locale).select(count) === 'one' ? `${key}_one` : `${key}_other`;
}
