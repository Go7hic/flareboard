function mergeLocale(partial: Partial<Record<string, string>>): Record<string, string> {
  const merged: Record<string, string> = { ...enUS };
  for (const key of Object.keys(partial)) {
    const value = partial[key];
    if (value !== undefined) merged[key] = value;
  }
  return merged;
}

